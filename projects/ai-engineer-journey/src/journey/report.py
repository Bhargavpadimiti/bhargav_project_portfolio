"""Generate the progress dashboard and keep generated tables in sync.

`journey report` writes PROGRESS.md and refreshes the blocks between
<!-- name:start --> / <!-- name:end --> markers in README files, so the
numbers on GitHub always match the progress files.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any

from . import store
from .plan import Plan, Week


def bar(fraction: float, width: int = 20) -> str:
    fraction = max(0.0, min(1.0, fraction))
    filled = round(fraction * width)
    return "█" * filled + "░" * (width - filled) + f" {fraction:.0%}"


def fmt_day(day: date, weekday: bool = False) -> str:
    """'1 Dec 2026' (or 'Tue 1 Dec 2026'). Avoids %-d, which Windows doesn't support."""
    text = f"{day.day} {day:%b %Y}"
    return f"{day:%a} {text}" if weekday else text


def fmt_range(start: date, end: date) -> str:
    if start.month == end.month:
        return f"{start.day}–{end.day} {end:%b %Y}"
    return f"{start.day} {start:%b} – {end.day} {end:%b %Y}"


def status_line(plan: Plan, today: date) -> str:
    number = plan.week_number(today)
    if number == 0:
        days = (plan.start_date - today).days
        return f"Starts {fmt_day(plan.start_date, weekday=True)} ({days} days to go)"
    if number > len(plan.weeks):
        return f"Programme complete ({fmt_day(plan.end_date)})"
    week = plan.week(number)
    phase = plan.phase(week.phase)
    return f"Week {number} of {len(plan.weeks)} · Phase {phase['id']}: {phase['name']}"


def current_or_first(plan: Plan, today: date) -> Week:
    number = plan.week_number(today)
    return plan.week(min(max(number, 1), len(plan.weeks)))


def plan_table(plan: Plan) -> str:
    rows = [
        "| Wk | Dates | Theme | Depth (understand) | Build (ship) |",
        "| -- | ----- | ----- | ------ | ----- |",
    ]
    for week in plan.weeks:
        checkpoint = plan.checkpoint(week.number)
        theme = f"**{week.title}**" + (f" 🏁 {checkpoint['name']}" if checkpoint else "")
        rows.append(
            f"| {week.number} | {fmt_range(week.start, week.end)} | {theme} "
            f"| {week.focus('depth') or '—'} | {week.focus('build') or '—'} |"
        )
    return "\n".join(rows)


def project_status(plan: Plan, projects_dir: Path, today: date) -> list[tuple[dict, str]]:
    current = plan.week_number(today)
    out = []
    for project in plan.projects:
        first, last = project["weeks"]
        if (projects_dir / project["id"]).is_dir():
            label = "🚧 Started"
        elif current > last:
            label = "⚠️ Overdue"
        else:
            label = f"⏳ Weeks {first}–{last}"
        out.append((project, label))
    return out


def dashboard(
    plan: Plan,
    sessions: list[store.Session],
    results: dict[str, Any],
    today: date,
    projects_dir: Path,
) -> str:
    week = current_or_first(plan, today)
    number = plan.week_number(today)
    total = store.hours_between(sessions, date.min, today)
    this_week = (
        store.hours_between(sessions, *plan.hours_window(week))
        if number <= len(plan.weeks)
        else 0.0
    )
    expected = plan.expected_hours(today)
    by_track = store.hours_by_track(sessions)
    elapsed = min(max(number - 1, 0), len(plan.weeks)) / len(plan.weeks)
    dates = f"{fmt_day(plan.start_date)} → {fmt_day(plan.end_date)}"
    overall = plan.total_hours
    streak = store.plural(store.streak(sessions, today), "day")
    tracks = " · ".join(f"{k} {v:g}" for k, v in by_track.items())

    lines = [
        "# Progress dashboard",
        "",
        f"_Generated by `journey report` on {fmt_day(today, weekday=True)}. Do not edit by hand._",
        "",
        f"Status: **{status_line(plan, today)}**",
        "",
        "| Measure | Now | Target |",
        "| ------- | --- | ------ |",
        f"| Programme elapsed | {bar(elapsed)} | {dates} |",
        f"| Hours logged | {total:g} h | {expected:g} h by today · {overall:g} h overall |",
        f"| Hours this week | {this_week:g} h | {plan.hours_per_week:g} h |",
        f"| Study streak | {streak} | most days, even 30 min |",
        f"| Hours by track | {tracks} | ~50% depth, ~40% build |",
        "",
        f"## This week: {week.title}",
        "",
        f"- **Depth:** {week.focus('depth') or '—'}",
        f"- **Build:** {week.focus('build') or '—'}",
    ]
    for item in week.items("deliverables"):
        lines.append(f"- [ ] {item}")

    lines += ["", "## Quizzes", ""]
    quizzes = results.get("quizzes") or {}
    if quizzes:
        lines += ["| Quiz | Best | Latest | Attempts |", "| ---- | ---- | ------ | -------- |"]
        for name, attempts in quizzes.items():
            best = store.best_attempt(attempts, "score", "total")
            latest = attempts[-1]
            lines.append(
                f"| {name} | {best['score']}/{best['total']} ({best['score'] / best['total']:.0%}) "
                f"| {latest['score']}/{latest['total']} on {latest['date']} | {len(attempts)} |"
            )
        lines.append("")
        lines.append("Target: **80%+** on every weekly quiz before moving on.")
    else:
        lines.append("No quizzes taken yet. Start with `journey quiz diagnostic`.")

    lines += ["", "## Exercises", ""]
    exercises = results.get("exercises") or {}
    if exercises:
        lines += ["| Set | Best | Latest run | Runs |", "| --- | ---- | ---------- | ---- |"]
        for name, attempts in exercises.items():
            best = store.best_attempt(attempts, "passed", "total")
            latest = attempts[-1]
            mark = " ✅" if best and best["passed"] == best["total"] else ""
            best_text = f"{best['passed']}/{best['total']}{mark}" if best else "—"
            latest_text = f"{latest['passed']}/{latest['total']} on {latest['date']}"
            lines.append(f"| {name} | {best_text} | {latest_text} | {len(attempts)} |")
        lines.append("")
        lines.append("Target: **every test passing**, including the edge cases.")
    else:
        lines.append("No exercises checked yet. Run `journey check week-01`.")

    lines += [
        "",
        "## Portfolio projects",
        "",
        "| Project | What it proves | Status |",
        "| ------- | -------------- | ------ |",
    ]
    for project, label in project_status(plan, projects_dir, today):
        lines.append(f"| {project['name']} | {project['aspect']} | {label} |")

    return "\n".join(lines) + "\n"


def readme_summary(
    plan: Plan, sessions: list[store.Session], results: dict[str, Any], today: date
) -> str:
    total = store.hours_between(sessions, date.min, today)
    number = plan.week_number(today)
    elapsed = min(max(number - 1, 0), len(plan.weeks)) / len(plan.weeks)
    quizzes = sum(len(v) for v in (results.get("quizzes") or {}).values())
    sets = results.get("exercises") or {}
    complete = sum(
        1
        for attempts in sets.values()
        if any(a["total"] and a["passed"] == a["total"] for a in attempts)
    )
    return "\n".join(
        [
            f"Status: **{status_line(plan, today)}**",
            "",
            f"`{bar(elapsed)}` of the programme · **{total:g} h** studied · "
            f"**{quizzes}** quiz attempts · **{complete}** exercise sets fully passing",
            "",
            f"Full dashboard: [PROGRESS.md](PROGRESS.md) (updated {fmt_day(today)})",
        ]
    )


def sync_block(path: Path, name: str, content: str) -> bool:
    """Replace the text between <!-- name:start --> and <!-- name:end -->.

    Returns True if the file changed.
    """
    start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
    if not path.is_file():
        return False
    text = path.read_text(encoding="utf-8")
    if start not in text or end not in text:
        return False
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    updated = f"{head}{start}\n{content}\n{end}{tail}"
    if updated != text:
        path.write_text(updated, encoding="utf-8")
        return True
    return False
